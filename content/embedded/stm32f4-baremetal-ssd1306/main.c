// --- Print Functions ---
void consolePrint(char text[]) {
    int counter = 0;
    while (text[counter] != '\0') {
        while (!(USART2->SR & USART_SR_TXE));
        USART2->DR = text[counter];
        counter++;
    }
}

void intPrint(int counter) {
    char digit[11];
    if (counter == 0) {
        consolePrint("0");
        return;
    }
    int i = 0;
    char temp[11];
    while (counter > 0) {
        temp[i] = (char)((counter % 10) + '0');
        i++;
        counter /= 10;
    }
    int j = 0;
    while (i > 0) {
        digit[j++] = temp[--i];
    }
    digit[j] = '\0';
    consolePrint(digit);
}
// --- I2C Related Functions

void I2C1Init(){
        // Reset and Clear to clean
        I2C1 -> CR1 |= I2C_CR1_SWRST;
        I2C1 -> CR1 &= ~I2C_CR1_SWRST;

        // Configuring the input Clock frequency
        I2C1 -> CR2 = 42U;

        //Configuring the I2C Clock control register
        I2C1 -> CCR = 210U;

        //Configuring the Max Rise Time
        I2C1 -> TRISE = 43U;

        // Enabling the peripheral
        I2C1 -> CR1 |= I2C_CR1_PE;
}

void OLEDWriteCommand(uint8_t cmd){
        I2C1 -> CR1 |= I2C_CR1_START;
        while(!(I2C1 -> SR1 & I2C_SR1_SB));
        I2C1 -> DR = OLED_ADDRESS;
        while (!(I2C1 -> SR1 & I2C_SR1_ADDR));
        (void) I2C1 -> SR1;
        (void) I2C1 -> SR2;
        //Send Control Byte (0x00 means next byte is a command)
        while (!(I2C1->SR1 & I2C_SR1_TXE));
        I2C1->DR = 0x00;
        while (!(I2C1->SR1 & I2C_SR1_TXE));
        I2C1->DR = cmd;

        while (!(I2C1->SR1 & I2C_SR1_BTF));
        I2C1 -> CR1 |= I2C_CR1_STOP;
}
void OLEDWriteData(uint8_t data){
        I2C1 -> CR1 |= I2C_CR1_START;
        while(!(I2C1 -> SR1 & I2C_SR1_SB));
        I2C1 -> DR = OLED_ADDRESS;
        while (!(I2C1 -> SR1 & I2C_SR1_ADDR));
        (void) I2C1 -> SR1;
        (void) I2C1 -> SR2;
        //Send Control Byte (0x40 means put the following byte directly into GDDRAM to light up pixels)
        while (!(I2C1->SR1 & I2C_SR1_TXE));
        I2C1->DR = 0x40;
        while (!(I2C1->SR1 & I2C_SR1_TXE));
        I2C1->DR = data;
        while (!(I2C1->SR1 & I2C_SR1_BTF));
        I2C1 -> CR1 |= I2C_CR1_STOP;
}

void OLEDCommandList(){
        OLEDWriteCommand(0xAE); // display OFF
        OLEDWriteCommand(0x20); // set Memory Addressing Mode
        OLEDWriteCommand(0x02); // 0x02 = Page Addressing Mode
        OLEDWriteCommand(0x8D); // charge Pump Command
        OLEDWriteCommand(0x14); // enable charge Pump
        OLEDWriteCommand(0xA4);
        OLEDWriteCommand(0xC8); // flip the screen
        OLEDWriteCommand(0xAF); // Display ON

}

void setCursor(uint8_t page, uint8_t column){
	OLEDWriteCommand(0xB0 | (page & 0x07)); // 0x07 is a safe guard to keep everything in range
	OLEDWriteCommand(0x00 | (column & 0x0F));
	OLEDWriteCommand(0x10 | ((column >> 4) & 0x0F));
}
void OLEDClear(){
	// Clearing the OLED screen
	for(int page =0; page<8;page++){
		setCursor(page,0);
		for(int column =0; column < 128 ; column++){
			// The display will auto increment for us
			OLEDWriteData(0x00);
		}
	}
}
