// --- Main Application ---
int main(void)
{
    HAL_Init();
    SystemClock_Config();

    // Initialize GPIO via HAL (handles PA2/PA3 for USART2)
    MX_GPIO_Init();

    // --- Enable Clocks ---
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;
    RCC->APB1ENR |= RCC_APB1ENR_USART2EN;
    RCC->APB1ENR |= RCC_APB1ENR_I2C1EN;

    // --- USART2 Setup ---
    USART2->BRR = 0x1117; // 42Mhz / 9600
    USART2->CR1 |= USART_CR1_TE | USART_CR1_UE;

    // --- I2C1 GPIO Setup (PB8 = SCL, PB9 = SDA) ---
    // Mode Register -->  Alternate Function Mode for both Pins
    GPIOB -> MODER &= ~GPIO_MODER_MODE8_0;
    GPIOB -> MODER |= GPIO_MODER_MODE8_1;
    GPIOB -> MODER &= ~GPIO_MODER_MODE9_0;
    GPIOB -> MODER |= GPIO_MODER_MODE9_1;

    // Output Type Register --> Open Drain For both Pins
    GPIOB -> OTYPER |= GPIO_OTYPER_OT8;
    GPIOB -> OTYPER |= GPIO_OTYPER_OT9;

    // Output Speed Register --> High Speed for both
    GPIOB -> OSPEEDR |= GPIO_OSPEEDR_OSPEED8_0;
    GPIOB -> OSPEEDR |= GPIO_OSPEEDR_OSPEED8_1;
    GPIOB -> OSPEEDR |= GPIO_OSPEEDR_OSPEED9_0;
    GPIOB -> OSPEEDR |= GPIO_OSPEEDR_OSPEED9_1;

    // Pull up Pull Down Register --> Pull Up for both Pins
    GPIOB -> PUPDR |= GPIO_PUPDR_PUPD8_0;
    GPIOB -> PUPDR &= ~GPIO_PUPDR_PUPD8_1;
    GPIOB -> PUPDR |= GPIO_PUPDR_PUPD9_0;
    GPIOB -> PUPDR &= ~GPIO_PUPDR_PUPD9_1;

    // Setting up the Alternate Function to AF4
    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH0_0;
    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH0_1;
    GPIOB -> AFR[1] |= GPIO_AFRH_AFRH0_2;
    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH0_3;

    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH1_0;
    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH1_1;
    GPIOB -> AFR[1] |= GPIO_AFRH_AFRH1_2;
    GPIOB -> AFR[1] &= ~GPIO_AFRH_AFRH1_3;

    I2C1Init();

    OLEDCommandList();
    drawLogo();
    consolePrint("OLED initialized.\r\n");
    while (1)
    {
        // Main loop
    }
}

